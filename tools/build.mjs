// Builds the two language pages and the sitemap from index.html + assets/js/content.js.
//
//   node tools/build.mjs
//
// index.html is the source page (Turkish). The script:
//   - fills every data-i18n / data-hint element with its text, so search engines and
//     link previews see real content without running JavaScript (main.js still renders at runtime),
//   - writes the SEO block between <!-- seo:start --> and <!-- seo:end --> (title, description,
//     canonical, hreflang, Open Graph, JSON-LD),
//   - writes en/index.html (English) from the same source,
//   - writes sitemap.xml, bumping <lastmod> only when a page actually changed.
//
// Run it after editing index.html or content.js, then commit the results.

